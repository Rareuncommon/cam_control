"""Generates lib/sdk/devices/models.dart from the Python SDK's model table.

The table is data — names, GATT UUIDs, firmware minimums and the layouts each
model can form — and its ORDER matters: a device is identified by the first
model whose advertised name matches, and a layout by the first setup that
matches. So it is generated from the live Python objects, in order, rather
than retyped.

Usage (from the repo root):
    <venv>/bin/python -I tool/sdk_port/gen_models.py
"""

from __future__ import annotations

from pathlib import Path

from edelkrone.devices import models
from edelkrone.devices._firmware_models import EXTRA_DEVICES

ROOT = Path(__file__).resolve().parent.parent.parent


def ident(model) -> str:
    for name in dir(models):
        if getattr(models, name) is model:
            return name
    raise KeyError(model.display_name)


def lit(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, str):
        return "'" + v.replace("'", "\\'") + "'"
    if hasattr(v, "value") and type(v).__name__ == "FirmwareType":
        return f"FirmwareType.{v.name}"
    raise TypeError(v)


def model_literal(m) -> str:
    setups = ",\n".join(
        f"      DeviceSetupSpec(EdlSetup.{s.setup.name}, [{', '.join('EdlDevice.' + d.name for d in s.devices)}])"
        for s in m.device_setups
    )
    pairable = (
        "null" if m.pairable_devices is None else "[" + ", ".join("EdlDevice." + d.name for d in m.pairable_devices) + "]"
    )
    return f"""EdelkroneDeviceModel(
    bleAdvName: {lit(m.ble_adv_name)},
    displayName: {lit(m.display_name)},
    deviceType: EdlDevice.{m.device_type.name},
    serviceUuid: {lit(m.service_uuid)},
    dataWriteUuid: {lit(m.data_write_uuid)},
    dataReadUuid: {lit(m.data_read_uuid)},
    ioctlWriteUuid: {lit(m.ioctl_write_uuid)},
    ioctlReadUuid: {lit(m.ioctl_read_uuid)},
    pairableDevices: {pairable},
    deviceLibrary: {lit(m.device_library)},
    deviceFirmwareName: {lit(m.device_firmware_name)},
    minimumMainVersion: {lit(m.minimum_main_version)},
    minimumRadioVersion: {lit(m.minimum_radio_version)},
    mainFirmwareType: {lit(m.main_firmware_type)},
    radioFirmwareType: {lit(m.radio_firmware_type)},
    bootloaderFirmwareType: {lit(m.bootlader_firmware_type)},
    deviceSetups: [
{setups}{',' if setups else ''}
    ],
  )"""


def camel_const(name: str) -> str:
    parts = name.lower().split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def main() -> None:
    out = [
        "// GENERATED by tool/sdk_port/gen_models.py from the edelkrone Python SDK",
        "// 0.1.0 (devices/models.py and devices/_firmware_models.py). Do not edit.",
        "//",
        "// Order is significant: identification takes the first model whose",
        "// advertised name matches, and layout resolution the first setup that",
        "// matches.",
        "//",
        "// Copyright (c) 2026 edelkrone. MIT licensed; see lib/sdk/LICENSE.",
        "",
        "import '../protocol/generated/moco.dart';",
        "import 'model_type.dart';",
        "",
    ]
    names = []
    defined = set()
    for m in models.ALL_DEVICES:
        n = camel_const(ident(m))
        names.append(n)
        # ALL_DEVICES lists TRIPOD_X twice upstream. The list keeps both
        # entries, faithfully; the constant is defined once.
        if n in defined:
            continue
        defined.add(n)
        out.append(f"const {n} = {model_literal(m)};")
        out.append("")
    extras = []
    for i, m in enumerate(EXTRA_DEVICES):
        import edelkrone.devices._firmware_models as fw

        n = next(k for k in dir(fw) if getattr(fw, k) is m)
        n = camel_const(n)
        extras.append(n)
        out.append(f"const {n} = {model_literal(m)};")
        out.append("")
    out.append("/// Every model, in the SDK's order.")
    out.append("const List<EdelkroneDeviceModel> allDevices = [" + ", ".join(names) + "];")
    out.append("")
    out.append("/// Firmware variants that advertise under a newer name.")
    out.append("const List<EdelkroneDeviceModel> extraDevices = [" + ", ".join(extras) + "];")
    out.append("")
    (ROOT / "lib/sdk/devices/models.dart").write_text("\n".join(out))
    print(f"{len(names)} models + {len(extras)} variants")


if __name__ == "__main__":
    main()
